# ── формулы: сырой замер → значение ──────────────────────────────────────────

def оформить(поле, значение):
    """Привести число к виду, в котором его хранит пресет. Строку не трогаем:
    так приходят значения, закреплённые вручную в слайсере."""
    if isinstance(значение, str):
        return значение
    if поле in ('nozzle_temperature', 'nozzle_temperature_initial_layer'):
        return str(int(round(значение)))
    if поле == 'pressure_advance':
        return '{:.4f}'.format(значение).rstrip('0').rstrip('.')
    if поле == 'filament_flow_ratio':
        return '{:.3f}'.format(значение)
    if поле == 'filament_shrink':
        return '{:.2f}%'.format(значение)
    return '{:.2f}'.format(значение)


def посчитать(тест, замер, поток_базы):
    """Замер → (значение, пояснение). Шкала теста лежит в тест['параметры']."""
    п, вид = тест['параметры'], тест['ввод']
    if вид == 'прямое':
        значение, пояснение = замер, 'взято как есть'
    elif вид == 'сдвиг':
        # Плитки подписаны прямой добавкой к коэффициенту. Сдвиг приходит списком:
        # повторный прогон печатается уже исправленным потоком, подписи считаются
        # от него, поэтому 0.98 + 0.02 + 0 = 1.000, а не 0.98.
        сдвиги = [float(с) for с in (замер if isinstance(замер, (list, tuple)) else [замер])]
        значение = round(поток_базы + sum(сдвиги), 3)
        if not 0.7 <= значение <= 1.3:
            raise Отказ('поток вышел {:.3f} — это далеко за разумным. Нужна подпись '
                        'плитки (от -0.05 до 0.05), а не сам коэффициент'.format(значение))
        пояснение = ' '.join(['{:g}'.format(поток_базы)] +
                             ['{} {:g}'.format('−' if с < 0 else '+', abs(с)) for с in сдвиги])
    elif вид == 'размер':
        if замер <= 0:
            raise Отказ('замер должен быть больше нуля')
        процент = п['номинал'] / замер * 100
        if not 97 <= процент <= 103:
            raise Отказ('усадка вышла {:.2f}% — похоже на замер не той грани или промах '
                        'осей, а не на свойство пластика'.format(процент))
        значение, пояснение = процент, '{:g} / {:g}'.format(п['номинал'], замер)
    elif вид == 'таблица':
        # Ступени башни отката у мастера Orca неравные, формулой не описываются.
        if замер < 0:
            raise Отказ('высота не может быть отрицательной')
        значение = next((з for граница, з in п['таблица'] if замер <= граница),
                        п['таблица'][-1][1])
        пояснение = 'по таблице ступеней башни'
    elif вид == 'высота_блоками':
        if замер < 0:
            raise Отказ('высота не может быть отрицательной')
        номер = max(0, math.floor(замер / п['высота_блока']))
        значение, пояснение = п['старт'] + номер * п['шаг'], 'блок №{} снизу'.format(номер)
    elif вид == 'высота_непрерывно':
        # Потолок разгона — «Конечный объёмный расход» из окна мастера. Выше него
        # башня печатается уже на потолке, линейная формула там завысила бы ответ.
        if замер < 0:
            raise Отказ('высота не может быть отрицательной')
        предел = п.get('конец') or п.get('предел')
        срыв = п['старт'] + замер * п['шаг_на_мм']
        срыв = min(срыв, предел) if предел else срыв
        запас = п.get('запас', 1.0)
        значение = срыв * запас
        if запас == 1.0:
            # Башня PA: значение растёт с высотой, запаса нет — берётся как есть.
            пояснение = 'высота {:g} мм по шкале башни'.format(замер)
        else:
            пояснение = 'срыв на {:.1f} мм³/с, минус запас {:.0%}'.format(срыв, 1 - запас)
    else:
        raise Отказ('неизвестный вид ввода: ' + вид)

    # У усадки свой, более широкий коридор выше: границы шкалы к ней не применялись
    # и в консольной версии, а сузить их молча — значит начать отвергать замеры.
    if вид != 'размер' and isinstance(значение, (int, float)):
        низ, верх = тест.get('границы') or [float('-inf'), float('inf')]
        if not низ <= значение <= верх:
            raise Отказ('вышло {:.3f}, а осмысленный диапазон {}…{}. Проверь замер '
                        'и шкалу теста'.format(значение, низ, верх))
    return значение, пояснение


