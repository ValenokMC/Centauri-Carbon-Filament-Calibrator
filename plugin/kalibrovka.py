def под_сопла(поля, шкалы):
    """Значения для остальных сопел: {сопло: {поле: значение}}.

    От диаметра сопла заметно зависят два параметра. Максимальный расход: на
    0.2 его режет само отверстие, на 0.6 и 0.8 упирается в хотэнд и не растёт.
    Pressure Advance: чем тоньше сопло, тем больше. Множители лежат в
    шкалы.json («сопла») и сняты с заводских профилей, где производитель задаёт
    значение на каждое сопло отдельно; откуда какой — написано там же.
    Это ОЦЕНКА, а не замер. Поток, усадка, температура и откат переносятся как есть.
    """
    итог = {}
    for сопло, множители in (шкалы.get('сопла') or {}).items():
        if not isinstance(множители, dict):
            continue
        свои = dict(поля)
        for поле, множитель in множители.items():
            if поле in свои:
                try:
                    свои[поле] = float(str(свои[поле]).rstrip('%')) * float(множитель)
                except ValueError:
                    pass
        итог[сопло] = свои
    return итог


def _файл_пресета(папка, имя):
    r"""Файл пользовательского пресета с таким именем в папке user\<кто>\filament.

    Пишем во ВСЕ папки пользователя, а не только туда, где пресет уже лежит. Какую
    папку читает Orca, зависит от входа в аккаунт: без входа — default, со входом —
    папку аккаунта. Катушки НИТ лежали только в папке аккаунта, и когда Orca после
    обновления оказалась без входа, они пропали из списка филаментов.
    Имя файла Orca выбирает сама, поэтому существующий файл ищем по имени внутри.
    """
    каталог = os.path.join(папка, 'filament')
    for путь in glob.glob(os.path.join(каталог, '*.json')):
        try:
            if _прочитать(путь, {}).get('name') == имя:
                return путь
        except (OSError, ValueError):
            continue
    return os.path.join(каталог, _имя_файла(имя) + '.json')


def _собрать_пресет(имя, база, поля, производитель, сопла):
    """Пресет-оверлей: только измеренное, остальное наследуется от базы."""
    пресет = {
        'compatible_printers': _совместимые_принтеры(сопла),
        'filament_vendor': производитель,
        'from': 'User', 'inherits': база, 'is_custom_defined': 0,
        'name': имя, 'filament_settings_id': имя,
        'version': _версия_пресетов(),
    }
    for поле, значение in sorted(поля.items()):
        пресет[поле] = [оформить(поле, значение)]
    if 'pressure_advance' in поля:
        пресет['enable_pressure_advance'] = ['1']
    return пресет


def записать_пресет(катушка, база, поля, производители, шкалы=None):
    """Основной пресет катушки и его варианты под остальные сопла.

    Orca не умеет держать в одном пресете филамента разные числа для разных
    сопел. Поэтому основной пресет совместим только с соплом, на котором
    калибровались, а на каждое другое заводится вариант «<катушка> @0.6 nozzle»
    с пересчитанными значениями. При смене сопла Orca сама показывает нужный.
    """
    шкалы = шкалы or _шкалы()
    производитель = _производитель(катушка, производители)
    принтер = _прочитать(os.path.join(_папка_катушки(катушка), 'принтер.json'), {}).get('имя')
    варианты = {} if принтер else под_сопла(поля, шкалы)
    основное = [_сопло_калибровки(шкалы)] if варианты else list(СОПЛА)
    свои = _пользовательские(катушка)
    дом = 'пользовательский' if свои else 'набор'

    def куда(имя):
        if свои:
            return [_файл_пресета(папка, имя) for папка in _папки_пользователя()]
        return _пути_набора(имя)

    пути = куда(катушка)
    if not свои:
        for путь in пути:
            мета = os.path.join(os.path.dirname(os.path.dirname(путь)), 'bundle_metadata.json')
            if not os.path.exists(мета):
                _записать(мета, МЕТА_НАБОРА, indent=4)
    основной = _собрать_пресет(катушка, база, поля, производитель, основное)
    if not принтер and not варианты:
        основной.pop('compatible_printers', None)
    if принтер:
        основной['compatible_printers'] = [принтер]
        основной['compatible_printers_condition'] = ''
    for путь in пути:
        _записать(путь, основной, indent=4, sort_keys=True)
    for сопло, свои_поля in варианты.items():
        имя = имя_под_сопло(катушка, сопло)
        вариант = _собрать_пресет(имя, база, свои_поля, производитель, [сопло])
        for путь in куда(имя):
            _записать(путь, вариант, indent=4, sort_keys=True)
    return {'дом': дом, 'пути': пути, 'сопел': len(варианты)}


def варианты_на_диске(катушка, шкалы):
    """Все ли варианты под сопла уже записаны."""
    нужно = [имя_под_сопло(катушка, с) for с, м in (шкалы.get('сопла') or {}).items()
             if isinstance(м, dict)]
    return all(_пользовательские(имя) or any(os.path.exists(п) for п in _пути_набора(имя))
               for имя in нужно)


