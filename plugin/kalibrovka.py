def нужные_базам():
    """Что спросить у Orca: {имя базы: [поля]}."""
    нужно = {}
    for описание in _шкалы()['материалы'].values():
        поля = нужно.setdefault(описание.get('база'), [])
        for тест in описание['тесты']:
            for поле in тест.get('поля', []):
                if поле not in поля:
                    поля.append(поле)
    поля = sorted({поле for список in нужно.values() for поле in список})
    нужно.pop(None, None)
    for строка in _журнал():
        if len(строка) > 3 and строка[3]:
            нужно[строка[3]] = поля
    return нужно


def _поток_базы(база, строго=False):
    """Коэффициент потока базы. Подставить единицу молча — значит сдвинуть поток
    на 2%: у профилей Elegoo база 0.98. Поэтому без снимка запись — отказ."""
    try:
        return float(str(_базы()[база]['filament_flow_ratio']).split(',', 1)[0])
    except (KeyError, ValueError, TypeError):
        if строго:
            raise Отказ('нет базовых значений профиля «{}». Они снимаются из Orca при '
                        'открытии вкладки — открой её в слайсере'.format(база))
        return None


# ── журнал и папки катушек ───────────────────────────────────────────────────

def _журнал():
    путь = _путь('Журнал.csv')
    if not os.path.exists(путь):
        return []
    with open(путь, encoding='utf-8-sig', newline='') as f:
        return [с for с in csv.reader(f, delimiter=';') if с][1:]


def _катушки_журнала():
    """[(материал, катушка, дата)] — по последней строке каждой катушки, свежие сверху."""
    видели, итог = set(), []
    for с in reversed(_журнал()):
        if len(с) >= 3 and с[2] not in видели:
            видели.add(с[2])
            итог.append((с[1], с[2], с[0]))
    return итог


def _записать_журнал(строка):
    """Обновить строку катушки, а не дописать новую: пресет пересобирается после
    каждого замера. Ключ — дата плюс имя: один прогон, одна запись."""
    строки = _журнал()
    for н, с in enumerate(строки):
        if len(с) > 2 and (с[0], с[2]) == (строка[0], строка[2]):
            строки[н] = строка
            break
    else:
        строки.append(строка)
    os.makedirs(ДАННЫЕ, exist_ok=True)
    with open(_путь('Журнал.csv'), 'w', encoding='utf-8-sig', newline='') as f:
        csv.writer(f, delimiter=';').writerows([ЗАГОЛОВОК_ЖУРНАЛА] + строки)


def _папка_катушки(имя):
    """Папка прогона: начатая, если есть, иначе на сегодня. Через listdir, а не
    glob: в именах катушек бывают символы, которые glob понял бы как шаблон."""
    корень = _путь('Катушки')
    было = sorted(п for п in (os.listdir(корень) if os.path.isdir(корень) else [])
                  if п[11:] == имя and os.path.isdir(os.path.join(корень, п)))
    return os.path.join(корень, было[-1] if было
                        else '{} {}'.format(datetime.date.today().isoformat(), имя))


