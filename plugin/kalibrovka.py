_host = {'snapshot': None}


def _plain(value):
    """Значение настройки как строка: Orca отдаёт список, строку или число."""
    value = getattr(value, 'value', value)
    if isinstance(value, (list, tuple)):
        value = value[0] if value else None
    return None if value is None else str(value)


def _resolved_raw(collection, name, key):
    """Значение поля с подъёмом по inherits — если пресет не развёрнут."""
    seen = set()
    while name and name not in seen:
        seen.add(name)
        preset = collection.find_preset(name)
        if preset is None:
            return None
        option = preset.config_value(key)
        value = getattr(option, 'value', option)
        if value is not None:
            return value
        name = _plain(preset.config_value('inherits'))
    return None


def _resolved(collection, name, key):
    return _plain(_resolved_raw(collection, name, key))


def snapshot_bases():
    """Сохранить базовые профили из живой Orca: 2.5 держит системные профили
    в бинарных .opc, с диска их не прочитать."""
    filaments = orca.host.preset_bundle().filaments
    profiles = dict(_базы())
    for name, keys in нужные_базам().items():
        if filaments.find_preset(name) is None:
            continue
        values = {key: _resolved(filaments, name, key) for key in keys}
        values = {key: value.split(',', 1)[0] for key, value in values.items() if value is not None}
        profiles[name] = {k: v for k, v in values.items() if v is not None}
    if not profiles:
        return 'ни один базовый профиль не найден в Orca'
    if _базы() != profiles:
        записать_базы(profiles, host_info().get('orca', ''))
        return 'снимок обновлён: {} профилей'.format(len(profiles))
    return 'снимок актуален: {} профилей'.format(len(profiles))


def host_info():
    info = {'режим': 'Orca', 'плагин': ЗДЕСЬ}
    try:
        app = getattr(orca.host, 'app_info', None)
        app = app() if callable(app) else {}
        info['orca'] = str(app.get('version', '')) if isinstance(app, dict) else str(app)
    except Exception as e:
        info['orca'] = 'app_info: %r' % e
    try:
        info['наборы'] = list(orca.host.preset.bundles.list_ids())
    except Exception as e:
        info['наборы'] = 'list_ids: %r' % e
    info['снимок_баз'] = _host['snapshot']
    return info


def reload_bundle():
    """Попросить Orca перечитать набор. True или текст причины."""
    try:
        bundles = orca.host.preset.bundles
        if НАБОР not in bundles.list_ids():
            return 'Orca не видит набор «{}».'.format(НАБОР)
        bundles.reload_local(НАБОР)
        return True
    except Exception as e:
        return '%s: %s.' % (type(e).__name__, e)


def selection():
    """Что сейчас выбрано в Orca — только имена и пара флагов."""
    bundle = orca.host.preset_bundle()
    printer = bundle.current_printer_preset()
    return {
        'принтер': printer.name, 'принтер_системный': bool(printer.is_system),
        'процесс': bundle.current_process_preset().name,
        'филаменты': list(bundle.current_filament_preset_names()),
        'несовместимые': [p.name for p in bundle.current_filament_presets()
                          if p is not None and not p.is_compatible],
    }


def _новая_в_orca(материал):
    bundle = orca.host.preset_bundle()
    names = list(bundle.current_filament_preset_names())
    if not names or not names[0]:
        raise Отказ('Выбери базовый профиль в первом слоте филамента Orca.')
    name = names[0]
    if материал not in _шкалы()['материалы']:
        raise Отказ('Выбери материал катушки.')
    filament_type = _resolved(bundle.filaments, name, 'filament_type')
    if filament_type and filament_type.split('-')[0] != материал.split('-')[0]:
        raise Отказ('Выбранный в Orca базовый профиль имеет тип {}.'.format(filament_type))
    if name not in [preset.name for preset in bundle.current_filament_presets() if preset and preset.is_compatible]:
        raise Отказ('Выбранный профиль филамента несовместим с принтером.')
    if any(_имя_катушки(name) in (имя, _имя_файла(имя)) for _, имя, _ in _катушки_журнала()):
        raise Отказ('Выбери исходный профиль филамента для новой катушки.')
    поля = {поле for тест in _шкалы()['материалы'][материал]['тесты'] for поле in тест['поля']}
    values = {поле: _plain(bundle.full_config_value(поле)) for поле in поля}
    profiles = _базы()
    profiles[name] = {key: value.split(',', 1)[0] for key, value in values.items() if value is not None}
    записать_базы(profiles, host_info().get('orca', ''))
    return {'база': name, 'принтер': bundle.current_printer_preset().name}


def _активная_плита():
    bundle = orca.host.preset_bundle()
    printer = bundle.current_printer_preset()
    names = list(bundle.current_filament_preset_names())
    if not names or not names[0]:
        raise Отказ('Выбери филамент в первом слоте Orca.')
    def current(key):
        return _plain(bundle.full_config_value(key))

    def number(key, value):
        try:
            return float(value.split(',', 1)[0])
        except (AttributeError, ValueError) as error:
            raise Отказ('В активном профиле Orca не удалось прочитать {}.'.format(key)) from error

    points = bundle.full_config_value('printable_area')
    if not points:
        raise Отказ('В профиле Orca отсутствует печатная область.')
    if isinstance(points, str):
        points = points.split(',')
    points = [tuple(map(float, p.split('x'))) if isinstance(p, str) else tuple(map(float, p))
              for p in points]
    if current('belt_printer') in ('1', 'True'):
        raise Отказ('Для ленточного принтера используй штатные тесты Orca.')
    xs, ys = zip(*points)
    x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)
    if sys.platform != 'win32':
        raise Отказ('Эта сборка плагина проверяется на Orca для Windows.')
    import ctypes
    exe = ctypes.create_unicode_buffer(32768)
    if not ctypes.WinDLL('kernel32').GetModuleFileNameW(None, exe, len(exe)):
        raise Отказ('Не удалось определить папку установленной Orca.')
    return {
        'принтер': printer.name, 'филамент': names[0],
        'сопло': number('nozzle_diameter', current('nozzle_diameter')), 'диалект': current('gcode_flavor'),
        'поток_филамента': number('filament_flow_ratio', current('filament_flow_ratio')),
        'поток_процесса': number('print_flow_ratio', current('print_flow_ratio') or '1'),
        'ресурсы': Path(exe.value).parent / 'resources', 'начало': (x0, y0),
        'стол': (x1 - x0, y1 - y0), 'центр': ((x0 + x1) / 2, (y0 + y1) / 2),
        'границы': (x0, y0, x1, y1), 'высота': number('printable_height', current('printable_height')),
    }


def _cstyle(values):
    """Строка в формате Slic3r::escape_strings_cstyle — так Orca кодирует
    список путей в сообщении между своими экземплярами."""
    out = []
    for value in values:
        if any(c in value for c in ' \t;\\"\r\n'):
            value = '"' + (value.replace('\\', '\\\\').replace('"', '\\"')
                           .replace('\r', '\\r').replace('\n', '\\n')) + '"'
        out.append(value)
    return ';'.join(out)


def open_in_this_window(path):
    """Загрузить проект в ЭТО окно Orca, как при двойном щелчке по 3MF.

    У плагинов нет вызова «открыть проект». Зато у Orca есть свой канал: второй
    запущенный экземпляр передаёт первому пути файлов сообщением WM_COPYDATA
    (InstanceCheck.cpp), и главное окно грузит их через Plater::load_files().
    Плагин живёт внутри процесса Orca и шлёт то же сообщение своему же окну.
    Приём подсмотрен в плагине PlatePilot; os.startfile вместо него открывал
    второе окно слайсера, а без ассоциации .3mf — диалог Windows «чем открыть».
    """
    import ctypes
    from ctypes import wintypes

    class COPYDATASTRUCT(ctypes.Structure):
        _fields_ = [('dwData', ctypes.c_size_t), ('cbData', wintypes.DWORD),
                    ('lpData', ctypes.c_void_p)]

    user = ctypes.WinDLL('user32')
    kernel = ctypes.WinDLL('kernel32')
    user.GetPropW.restype = ctypes.c_void_p
    user.GetPropW.argtypes = [wintypes.HWND, wintypes.LPCWSTR]
    user.SendMessageW.restype = ctypes.c_ssize_t
    user.SendMessageW.argtypes = [wintypes.HWND, wintypes.UINT, wintypes.WPARAM, ctypes.c_void_p]
    pid = kernel.GetCurrentProcessId()
    found = []

    @ctypes.WINFUNCTYPE(wintypes.BOOL, wintypes.HWND, wintypes.LPARAM)
    def visit(hwnd, _):
        owner = wintypes.DWORD()
        user.GetWindowThreadProcessId(hwnd, ctypes.byref(owner))
        if owner.value == pid:
            name = ctypes.create_unicode_buffer(256)
            user.GetClassNameW(hwnd, name, 256)
            # Главное окно несёт свойства Instance_Hash_*, остальные окна процесса — нет.
            if name.value == 'wxWindowNR' and (user.GetPropW(hwnd, 'Instance_Hash_Minor')
                                               or user.GetPropW(hwnd, 'Instance_Hash_Major')):
                found.append(hwnd)
                return False
        return True

    user.EnumWindows(visit, 0)
    if not found:
        raise OSError('не нашёл главное окно Orca')
    exe = ctypes.create_unicode_buffer(32768)
    kernel.GetModuleFileNameW(None, exe, len(exe))
    # Первое значение получатель пропускает: это путь отправившей программы.
    text = ctypes.create_unicode_buffer(_cstyle([exe.value, os.path.abspath(path)]))
    data = COPYDATASTRUCT(1, ctypes.sizeof(text), ctypes.cast(text, ctypes.c_void_p))
    user.SendMessageW(found[0], 0x004A, 0, ctypes.byref(data))      # WM_COPYDATA


def handle(message):
    if not isinstance(message, dict):
        try:
            message = json.loads(message)
        except (TypeError, ValueError):
            message = {}
    action = message.get('действие')
    reply = {'id': message.get('id'), 'действие': action}
    try:
        if action == 'состояние':
            if _host['snapshot'] is None:
                try:
                    _host['snapshot'] = snapshot_bases()
                except Exception as e:
                    _host['snapshot'] = 'не снят: %s: %s' % (type(e).__name__, e)
            reply = обработать(message)
            if reply.get('ок'):
                reply['состояние']['принтер'] = selection()['принтер']
            reply['хост'] = host_info()
        elif action == 'плита':
            reply = обработать(message, _активная_плита())
            if reply.get('ок') and message.get('открыть'):
                try:
                    open_in_this_window(reply['путь'])
                    reply['открыто'] = True
                except Exception as e:
                    reply['открыто'] = '%s: %s' % (type(e).__name__, e)
        elif action == 'выбор':
            chosen = selection()
            reply.update(ок=True, выбор=chosen, замечания=проверить_выбор(chosen))
        else:
            context = _новая_в_orca(message['материал']) if action == 'новая' else None
            reply = обработать(message, context)
            preset = reply.get('пресет')
            if reply.get('ок') and isinstance(preset, dict) and preset.get('дом') == 'набор':
                preset['перечитано'] = reload_bundle()
    except Exception as e:
        reply.update(ок=False, ошибка='%s: %s' % (type(e).__name__, e),
                     след=traceback.format_exc())
    return reply


