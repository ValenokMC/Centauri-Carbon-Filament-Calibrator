def плита_теста(ключ, параметры, стол=(256.0, 256.0), сопло=0.4, **условия):
    """Описание плиты. стол — (ширина, глубина) печатной области, мм."""
    if ключ not in _ПЛИТЫ:
        raise ValueError('нет своей модели для теста: ' + ключ)
    плита = _ПЛИТЫ[ключ](параметры, стол, сопло, **условия)
    края = [1e9, 1e9, 0.0, -1e9, -1e9, 0.0]
    for объект in плита['объекты']:
        x0, y0, z0, x1, y1, z1 = габарит(объект['сетка'])
        if объект['место'] == 'середина':
            объект['место'] = (стол[0] / 2 - (x0 + x1) / 2, стол[1] / 2 - (y0 + y1) / 2)
        мx, мy = объект['место']
        края = [min(края[0], мx + x0), min(края[1], мy + y0), 0.0,
                max(края[3], мx + x1), max(края[4], мy + y1), max(края[5], z1)]
    плита['габарит'] = tuple(round(v, 3) for v in края)
    for поле in ('плита', 'процесс', 'филамент'):
        плита.setdefault(поле, {})
    плита.setdefault('команды', [])
    return плита


