def _xml(текст):
    return (str(текст).replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
            .replace('"', '&quot;').replace('\n', '&#10;'))


_ТИПЫ = ('<?xml version="1.0" encoding="UTF-8"?>\n'
         '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">\n'
         ' <Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>\n'
         ' <Default Extension="model" ContentType="application/vnd.ms-package.3dmanufacturing-3dmodel+xml"/>\n'
         ' <Default Extension="config" ContentType="application/xml"/>\n'
         ' <Default Extension="json" ContentType="application/json"/>\n'
         ' <Default Extension="xml" ContentType="application/xml"/>\n'
         '</Types>\n')
_СВЯЗИ = ('<?xml version="1.0" encoding="UTF-8"?>\n'
          '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">\n'
          ' <Relationship Target="/3D/3dmodel.model" Id="rel-1" '
          'Type="http://schemas.microsoft.com/3dmanufacturing/2013/01/3dmodel"/>\n'
          '</Relationships>\n')


def _модель(плита, заголовок, шапка):
    строки = ['<?xml version="1.0" encoding="UTF-8"?>',
              '<model unit="millimeter" xml:lang="en-US" '
              'xmlns="http://schemas.microsoft.com/3dmanufacturing/core/2015/02">']
    строки.extend('<metadata name="{}">{}</metadata>'.format(_xml(к), _xml(з)) for к, з in шапка)
    строки.append('<metadata name="Title">{}</metadata>'.format(_xml(заголовок)))
    строки.append('<resources>')
    for н, объект in enumerate(плита['объекты'], 1):
        вершины, треугольники = объект['сетка']
        строки.append('<object id="{}" type="model" name="{}">'.format(н, _xml(объект['имя'])))
        строки.append('<mesh><vertices>')
        строки.extend('<vertex x="{}" y="{}" z="{}"/>'.format(x, y, z) for x, y, z in вершины)
        строки.append('</vertices><triangles>')
        строки.extend('<triangle v1="{}" v2="{}" v3="{}"/>'.format(a, b, c) for a, b, c in треугольники)
        строки.append('</triangles></mesh></object>')
    строки.append('</resources><build>')
    for н, объект in enumerate(плита['объекты'], 1):
        строки.append('<item objectid="{}" transform="1 0 0 0 1 0 0 0 1 {} {} 0" printable="1"/>'.format(
            н, _число(объект['место'][0]), _число(объект['место'][1])))
    строки.append('</build></model>')
    return '\n'.join(строки) + '\n'


def _настройки_модели(плита):
    строки = ['<?xml version="1.0" encoding="UTF-8"?>', '<config>']
    for н, объект in enumerate(плита['объекты'], 1):
        строки.append('  <object id="{}">'.format(н))
        строки.append('    <metadata key="name" value="{}"/>'.format(_xml(объект['имя'])))
        строки.append('    <metadata key="extruder" value="1"/>')
        for к in sorted(объект['настройки']):
            строки.append('    <metadata key="{}" value="{}"/>'.format(к, _xml(объект['настройки'][к])))
        строки.append('  </object>')
    строки.extend(['  <plate>', '    <metadata key="plater_id" value="1"/>',
                   '    <metadata key="plater_name" value=""/>', '    <metadata key="locked" value="false"/>'])
    for к in sorted(плита['плита']):
        строки.append('    <metadata key="{}" value="{}"/>'.format(к, _xml(плита['плита'][к])))
    for н in range(1, len(плита['объекты']) + 1):
        строки.extend(['    <model_instance>', '      <metadata key="object_id" value="{}"/>'.format(н),
                       '      <metadata key="instance_id" value="0"/>', '    </model_instance>'])
    строки.extend(['  </plate>', '</config>'])
    return '\n'.join(строки) + '\n'


def _команды_по_высоте(команды):
    строки = ['<?xml version="1.0" encoding="utf-8"?>', '<custom_gcodes_per_layer>', '<plate>',
              '<plate_info id="1"/>']
    строки.extend('<layer top_z="{:.2f}" type="4" extruder="1" color="" extra="{}"/>'.format(z, _xml(текст))
                  for z, текст in команды)
    строки.extend(['<mode value="SingleExtruder"/>', '</plate>', '</custom_gcodes_per_layer>'])
    return '\n'.join(строки) + '\n'


def записать_3mf(путь, плита, конфиг_json=None, заголовок='Калибровка', версия='2.5.0', опубликовано=None):
    """Записать проект плиты.

    конфиг_json — готовый текст Metadata/project_settings.config: обычный проект Orca.
    опубликовано — {'ключи': [...], 'материал': [...], 'значения': {ключ: значение}}:
    «опубликованный» проект Orca 2.5. Он не несёт пресетов: слайсер оставляет принтер,
    процесс и филамент, выбранные у пользователя, и накладывает только перечисленное.
    """
    import json
    if опубликовано is not None:
        значения = ''.join('{} = {}\n'.format(к, з) for к, з in sorted(опубликовано['значения'].items()))
        шапка = [('orca_published', '1'),
                 ('orca_published_keys', json.dumps(sorted(опубликовано.get('ключи', [])))),
                 ('orca_published_material_keys', json.dumps(опубликовано.get('материал', []), ensure_ascii=False)),
                 ('orca_published_config', значения)]
    else:
        шапка = [('Application', 'OrcaSlicer ' + версия)]
    файлы = [('[Content_Types].xml', _ТИПЫ), ('_rels/.rels', _СВЯЗИ),
             ('3D/3dmodel.model', _модель(плита, заголовок, шапка)),
             ('Metadata/model_settings.config', _настройки_модели(плита))]
    if конфиг_json is not None and опубликовано is None:
        файлы.append(('Metadata/project_settings.config', конфиг_json))
        файлы.append(('Metadata/slice_info.config',
                      '<?xml version="1.0" encoding="UTF-8"?>\n<config>\n  <header>\n'
                      '    <header_item key="OrcaSlicer-Version" value="{}"/>\n  </header>\n</config>\n'.format(версия)))
    if плита['команды']:
        файлы.append(('Metadata/custom_gcode_per_layer.xml', _команды_по_высоте(плита['команды'])))
    with zipfile.ZipFile(путь, 'w', zipfile.ZIP_DEFLATED) as z:
        for имя, текст in файлы:
            z.writestr(имя, текст if isinstance(текст, bytes) else текст.encode('utf-8'))
    return путь
