r"""
Свои модели калибровочных плит и запись проекта 3MF.

Настройки тестов, брусок усадки и запись проекта 3MF. Штатные сетки
башен передаются при сборке плиты.

Модуль ничего не знает про Orca, катушки и журнал. На входе — параметры теста из
шкалы и размеры стола, на выходе — описание плиты:

    {'объекты':  [{'имя', 'сетка': (вершины, треугольники), 'место': (x, y), 'настройки': {...}}],
     'плита':    {...}            настройки плиты (ваза)
     'команды':  [(высота, текст)] G-code по высоте
     'процесс':  {...}            что плита меняет в процессе
     'филамент': {...}            что плита меняет в филаменте
     'размер':   (x, y, z)        габарит напечатанного, для проверок}

build.py включает этот модуль в установочный файл плагина.
"""
import json
import math
import zipfile

__all__ = ['плита_теста', 'записать_3mf', 'проверить_сетку', 'сечение_линии', 'ВЫСОТА_PA']

ВЫСОТА_PA = 50.0        # башня PA: на эту высоту растянут весь диапазон значений


# ── сетки ────────────────────────────────────────────────────────────────────
# Сетка — пара (вершины, треугольники). Обход треугольника против часовой, если
# смотреть снаружи. Объект — несколько замкнутых оболочек, слегка заходящих друг
# в друга: слайсер объединяет их сам.

def брус(x0, y0, z0, x1, y1, z1):
    в = [(x0, y0, z0), (x1, y0, z0), (x1, y1, z0), (x0, y1, z0),
         (x0, y0, z1), (x1, y0, z1), (x1, y1, z1), (x0, y1, z1)]
    т = [(0, 2, 1), (0, 3, 2), (4, 5, 6), (4, 6, 7), (0, 1, 5), (0, 5, 4),
         (1, 2, 6), (1, 6, 5), (2, 3, 7), (2, 7, 6), (3, 0, 4), (3, 4, 7)]
    return в, т


def призма(контур, y0, y1):
    """Выпуклый контур в плоскости XZ, вытянутый вдоль Y."""
    n = len(контур)
    в = [(x, y0, z) for x, z in контур] + [(x, y1, z) for x, z in контур]
    т = []
    for i in range(1, n - 1):
        т.append((0, i, i + 1))
        т.append((n, n + i + 1, n + i))
    for i in range(n):
        j = (i + 1) % n
        т.append((i, n + i, n + j))
        т.append((i, n + j, j))
    return _наружу((в, т))


def столб(контур, z0, z1):
    """Выпуклый контур в плоскости XY, вытянутый вдоль Z."""
    в, т = призма([(x, y) for x, y in контур], z0, z1)
    return _наружу(([(x, z, y) for x, y, z in в], т))


def _объём(сетка):
    в, т = сетка
    сумма = 0.0
    for a, b, c in т:
        (x1, y1, z1), (x2, y2, z2), (x3, y3, z3) = в[a], в[b], в[c]
        сумма += x1 * (y2 * z3 - y3 * z2) - y1 * (x2 * z3 - x3 * z2) + z1 * (x2 * y3 - x3 * y2)
    return сумма / 6.0


def _наружу(сетка):
    в, т = сетка
    return (в, т) if _объём(сетка) > 0 else (в, [(a, c, b) for a, b, c in т])


def склеить(части):
    в, т = [], []
    for чв, чт in части:
        сдвиг = len(в)
        в.extend(чв)
        т.extend((a + сдвиг, b + сдвиг, c + сдвиг) for a, b, c in чт)
    return в, т


def проверить_сетку(сетка):
    """Список замечаний; пустой — каждое ребро принадлежит ровно двум треугольникам
    и пройдено ими в противоположные стороны, объём положительный."""
    в, т = сетка
    рёбра = {}
    for a, b, c in т:
        for p, q in ((a, b), (b, c), (c, a)):
            рёбра[(p, q)] = рёбра.get((p, q), 0) + 1
    плохо = [р for р, сколько in рёбра.items() if сколько != 1 or рёбра.get((р[1], р[0])) != 1]
    замечания = []
    if плохо:
        замечания.append('незамкнутых или двойных рёбер: {}'.format(len(плохо)))
    if _объём(сетка) <= 0:
        замечания.append('объём не положительный')
    return замечания


def габарит(сетка):
    в = сетка[0]
    return (min(p[0] for p in в), min(p[1] for p in в), min(p[2] for p in в),
            max(p[0] for p in в), max(p[1] for p in в), max(p[2] for p in в))


# ── подписи: семисегментные цифры ────────────────────────────────────────────

ЗНАК_Ш, ЗНАК_В, ЗНАК_Т, ЗНАК_ШАГ = 3.0, 5.4, 0.8, 0.9
_СЕГМЕНТЫ = {
    'a': (0, ЗНАК_В - ЗНАК_Т, ЗНАК_Ш, ЗНАК_В), 'd': (0, 0, ЗНАК_Ш, ЗНАК_Т),
    'g': (0, (ЗНАК_В - ЗНАК_Т) / 2, ЗНАК_Ш, (ЗНАК_В + ЗНАК_Т) / 2),
    'f': (0, ЗНАК_В / 2, ЗНАК_Т, ЗНАК_В), 'b': (ЗНАК_Ш - ЗНАК_Т, ЗНАК_В / 2, ЗНАК_Ш, ЗНАК_В),
    'e': (0, 0, ЗНАК_Т, ЗНАК_В / 2), 'c': (ЗНАК_Ш - ЗНАК_Т, 0, ЗНАК_Ш, ЗНАК_В / 2),
}
_ЦИФРЫ = {'0': 'abcdef', '1': 'bc', '2': 'abged', '3': 'abgcd', '4': 'fgbc', '5': 'afgcd',
          '6': 'afgedc', '7': 'abc', '8': 'abcdefg', '9': 'abcdfg', '-': 'g'}


def _знаки(текст):
    """Прямоугольники подписи в её собственных координатах и её ширина."""
    прямоугольники, x = [], 0.0
    for знак in текст:
        if знак == '.':
            прямоугольники.append((x, 0, x + ЗНАК_Т, ЗНАК_Т))
            x += ЗНАК_Т + ЗНАК_ШАГ
            continue
        for сегмент in _ЦИФРЫ[знак]:
            u0, v0, u1, v1 = _СЕГМЕНТЫ[сегмент]
            прямоугольники.append((x + u0, v0, x + u1, v1))
        x += ЗНАК_Ш + ЗНАК_ШАГ
    return прямоугольники, x - ЗНАК_ШАГ


def подпись_сверху(текст, середина_x, y, z, выступ=0.4):
    """Подпись на горизонтальной грани: читается сверху, выступает вверх."""
    прямоугольники, ширина = _знаки(текст)
    x = середина_x - ширина / 2
    return [брус(x + u0, y + v0, z - 0.2, x + u1, y + v1, z + выступ) for u0, v0, u1, v1 in прямоугольники]


def подпись_спереди(текст, середина_x, y, z, выступ=0.6):
    """Подпись на передней грани (y — её плоскость): выступает к наблюдателю."""
    прямоугольники, ширина = _знаки(текст)
    x = середина_x - ширина / 2
    return [брус(x + u0, y - выступ, z + v0, x + u1, y + 0.2, z + v1) for u0, v0, u1, v1 in прямоугольники]


# ── расчёты ──────────────────────────────────────────────────────────────────

def сечение_линии(ширина, слой):
    """Площадь сечения уложенной линии, мм² — та же формула, что у слайсера."""
    return (ширина - слой * (1 - math.pi / 4)) * слой


def _число(значение):
    текст = '{:.4f}'.format(значение).rstrip('0').rstrip('.')
    return текст if текст not in ('', '-0') else '0'


def _команда_pa(диалект, значение):
    if диалект in ('marlin', 'marlin2'):
        return 'M900 K{}'.format(_число(значение))
    if диалект in ('reprapfirmware', 'reprap'):
        return 'M572 D0 S{}'.format(_число(значение))
    return 'SET_PRESSURE_ADVANCE ADVANCE={}'.format(_число(значение))


# ── плиты ────────────────────────────────────────────────────────────────────

def _температура(п, стол, сопло, штатная=None, **_):
    """Башня: два столба, между ними мост на верху каждого блока, по бокам
    нависания 45° и 55°, на левом столбе — температура блока."""
    блок = float(п.get('высота_блока', 10))
    шаг = float(п['шаг'])
    блоков = int(round((float(п['конец']) - float(п['старт'])) / шаг)) + 1
    глубина, столб_ш, пролёт = 10.0, 12.0, 24.0
    правый = столб_ш + пролёт
    высота = блоков * блок
    части = [] if штатная else [брус(0, 0, 0, столб_ш, глубина, высота), брус(правый, 0, 0, правый + столб_ш, глубина, высота)]
    команды = []
    for н in range(блоков):
        низ = н * блок
        температура = int(round(float(п['старт']) + н * шаг))
        if not штатная:
            # мост: печатается последним в блоке, значит, на температуре этого блока
            части.append(брус(столб_ш - 0.3, 0, низ + блок - 1.4, правый + 0.3, глубина, низ + блок))
            части.append(призма([(0.2, низ + 1.0), (0.2, низ + 7.0), (-6.0, низ + 7.0)], 0, глубина))
            край = правый + столб_ш
            части.append(призма([(край - 0.2, низ + 1.0), (край + 8.0, низ + 6.5), (край - 0.2, низ + 6.5)], 0, глубина))
            части.extend(подпись_спереди(str(температура), столб_ш / 2, 0, низ + 1.6))
        if н:
            команды.append((низ, 'M104 S{}'.format(температура)))
    сетка = штатная or склеить(части)
    return {
        'объекты': [{'имя': 'Башня температуры', 'сетка': сетка, 'место': 'середина',
                     'настройки': {'brim_type': 'outer_only', 'brim_width': '5', 'brim_object_gap': '0',
                                   'layer_height': '0.2', 'seam_slope_type': 'none',
                                   'enable_support': '0'}}],
        'команды': команды,
        'филамент': {'nozzle_temperature': _число(float(п['старт'])),
                     'nozzle_temperature_initial_layer': _число(float(п['старт']))},
    }


def _поток(п, стол, сопло, поток_базы=1.0, поток_процесса=1.0, **_):
    """Плитки со сдвигом коэффициента потока. Подпись — на полке спереди, чтобы
    оценочная поверхность оставалась чистой.

    Коэффициент у объекта ЗАМЕНЯЕТ общий коэффициент потока из процесса, а не
    умножается на него. Если в процессе стоит не единица (у профилей Elegoo — 0.97),
    плитка без этой поправки печаталась бы гуще обычной детали, и найденный по ней
    поток оказался бы занижен. Поэтому общий коэффициент входит в каждую плитку."""
    шаг, предел = float(п['шаг']), float(п['предел'])
    число = int(round(предел / шаг))
    сторона, полка, толщина, зазор = 30.0, 8.0, 2.4, 5.0
    в_ряду = max(1, min(4, int((стол[0] - 20 + зазор) // (сторона + зазор))))
    сдвиги = [round(н * шаг, 4) for н in range(-число, число + 1)]
    рядов = int(math.ceil(len(сдвиги) / float(в_ряду)))
    шаг_x, шаг_y = сторона + зазор, сторона + полка + зазор
    ширина, глубина = в_ряду * шаг_x - зазор, рядов * шаг_y - зазор
    объекты = []
    for н, сдвиг in enumerate(сдвиги):
        части = [брус(0, 0, 0, сторона, сторона + полка, толщина)]
        части.extend(подпись_сверху(_число(сдвиг), сторона / 2, 1.3, толщина))
        # бортик между полкой с подписью и оценочной поверхностью
        части.append(брус(0, полка - 0.6, толщина - 0.2, сторона, полка, толщина + 0.4))
        ряд, колонка = divmod(н, в_ряду)
        объекты.append({
            'имя': 'Поток {}'.format(_число(сдвиг)), 'сетка': склеить(части),
            'место': (стол[0] / 2 - ширина / 2 + колонка * шаг_x,
                      стол[1] / 2 + глубина / 2 - (ряд + 1) * шаг_y + зазор),
            'метка': сдвиг,
            'настройки': {'print_flow_ratio': '{:.6f}'.format(поток_процесса * (поток_базы + сдвиг) / поток_базы),
                          'wall_loops': '1', 'top_shell_layers': '5', 'bottom_shell_layers': '2',
                          'top_shell_thickness': '0', 'bottom_shell_thickness': '0',
                          'sparse_infill_density': '35%', 'sparse_infill_pattern': 'rectilinear',
                          'top_surface_pattern': 'monotonic', 'only_one_wall_top': '1',
                          'ironing_type': 'no ironing', 'top_solid_infill_flow_ratio': '1',
                          'layer_height': '0.2', 'enable_support': '0', 'brim_type': 'no_brim'},
        })
    return {'объекты': объекты}


def _усадка(п, стол, сопло, **_):
    длина = float(п.get('номинал', 100.0))
    return {'объекты': [{'имя': 'Брусок усадки {} мм'.format(_число(длина)),
                         'сетка': брус(0, 0, 0, длина, 10.0, 3.0), 'место': 'середина',
                         'настройки': {'sparse_infill_density': '100%', 'enable_support': '0'}}]}


def _pa(п, стол, сопло, диалект='klipper', штатная=None, **_):
    """Башня с острыми углами: PA растёт с высотой, раз в миллиметр."""
    старт, конец = float(п['старт']), float(п['конец'])
    на_мм = (конец - старт) / ВЫСОТА_PA
    if not штатная:
        сторона = 50.0
        части = [брус(0, 0, 0, сторона, сторона, ВЫСОТА_PA + 1.0)]
        # Засечки каждые 5 мм и подписи каждые 10 — чтобы высоту можно было прочесть без
        # штангеля. Всё в середине передней грани: углы, по которым судят о PA, остаются чистыми.
        for мм in range(5, int(ВЫСОТА_PA) + 1, 5):
            части.append(брус(10.0 if мм % 10 == 0 else 14.0, -0.5, мм - 0.2, 18.0, 0.2, мм + 0.2))
        for мм in range(10, int(ВЫСОТА_PA) + 1, 10):
            части.extend(подпись_спереди(str(мм), 30.0, 0, мм - ЗНАК_В - 0.4))
    команды = [(float(мм), _команда_pa(диалект, старт + мм * на_мм)) for мм in range(1, int(ВЫСОТА_PA) + 1)]
    return {
        'объекты': [{'имя': 'Башня PA', 'сетка': штатная or склеить(части), 'место': 'середина',
                     'настройки': {'wall_loops': '2', 'sparse_infill_density': '0%', 'top_shell_layers': '0',
                                   'bottom_shell_layers': '1', 'layer_height': '0.2', 'seam_position': 'back',
                                   'seam_slope_type': 'none', 'brim_type': 'outer_only', 'brim_width': '4',
                                   'brim_object_gap': '0', 'enable_support': '0',
                                   'alternate_extra_wall': '0', 'detect_thin_wall': '0'}}],
        'команды': команды,
        'филамент': {'pressure_advance': _число(старт), 'enable_pressure_advance': '1',
                     'adaptive_pressure_advance': '0'},
        'на_мм': на_мм,
    }


def _скруглённый(длина, ширина, радиус, граней=8):
    контур = []
    for cx, cy, начало in ((длина - радиус, ширина - радиус, 0), (радиус, ширина - радиус, 90),
                           (радиус, радиус, 180), (длина - радиус, радиус, 270)):
        for н in range(граней + 1):
            угол = math.radians(начало + 90.0 * н / граней)
            контур.append((cx + радиус * math.cos(угол), cy + радиус * math.sin(угол)))
    return контур


def _макс_расход(п, стол, сопло, поток_процесса=1.0, штатная=None, **_):
    """Башня вазой: одна стенка без шва, скорость растёт с высотой. Скорость стенки
    задана так, чтобы 100 % отвечали верхней точке шкалы, — прошивке не приходится
    разгонять печать выше заданного."""
    старт, конец, на_мм = float(п['старт']), float(п['конец']), float(п['шаг_на_мм'])
    # Слой 0.7 сопла укладывается в «макс. высоту слоя» обычных профилей принтера:
    # менять настройки принтера плите не приходится.
    слой, линия = round(сопло * 0.7, 2), round(сопло * 1.75, 2)
    # Общий коэффициент потока из процесса уменьшает выдавленный объём — так же его
    # видит и ограничитель расхода в слайсере, поэтому он входит в расчёт скорости.
    сечение = сечение_линии(линия, слой) * поток_процесса
    скорость = конец / сечение
    высота = (конец - старт) / на_мм + 2.0
    длина = max(80.0, min(160.0, стол[0] - 60.0))
    ширина = max(40.0, min(60.0, стол[1] - 60.0))
    # Проценты с одним знаком после запятой: у мягких пластиков шкала начинается с
    # единиц мм³/с, и округление до целого процента давало бы ошибку в несколько процентов.
    доля = lambda расход: 'M220 S{}'.format(_число(round(расход / конец * 100, 1)))
    команды = [(round(2 * слой, 2), доля(старт))]
    for мм in range(1, int(math.floor(высота)) + 1):
        расход = min(конец, старт + мм * на_мм)
        команды.append((float(мм), доля(расход)))
    return {
        'объекты': [{'имя': 'Башня расхода', 'сетка': штатная or столб(_скруглённый(длина, ширина, 15.0), 0, высота),
                     'место': 'середина',
                     'настройки': {'layer_height': _число(слой), 'outer_wall_line_width': _число(линия),
                                   'outer_wall_speed': _число(round(скорость, 1)), 'wall_loops': '1',
                                   'sparse_infill_density': '0%', 'top_shell_layers': '0',
                                   'bottom_shell_layers': '0', 'brim_type': 'outer_and_inner',
                                   'brim_width': '5', 'brim_object_gap': '0', 'enable_overhang_speed': '0',
                                   'alternate_extra_wall': '0', 'precise_z_height': '0',
                                   'enable_support': '0'}}],
        'плита': {'spiral_mode': 'true'},
        'команды': команды,
        'процесс': {'spiral_mode': '1'},
        'филамент': {'filament_max_volumetric_speed': '200', 'slow_down_for_layer_cooling': '0'},
        'скорость': скорость, 'сечение': сечение,
    }


def _заглушка(п, стол, сопло, **_):
    """Проект не может быть пустым. Мастер калибровки Orca заменит брусок своей моделью."""
    return {'объекты': [{'имя': 'Заглушка — мастер калибровки заменит её',
                         'сетка': брус(0, 0, 0, 20.0, 10.0, 2.0), 'место': 'середина', 'настройки': {}}]}


def _ретракт(п, стол, сопло, диалект, откат_профиля, **_):
    """Пара столбиков для уже включённого отката через прошивку."""
    if откат_профиля is None:
        шаблон = None
    elif диалект == 'klipper':
        шаблон = 'SET_RETRACTION RETRACT_LENGTH={}'
    elif диалект in ('marlin', 'marlin2'):
        шаблон = 'M207 S{}'
    else:
        raise ValueError('Неизвестная команда отката для ' + диалект)
    таблица = п['таблица']
    конец = таблица[-1][0]
